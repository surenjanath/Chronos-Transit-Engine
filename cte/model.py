def _real_split():
    """Real Kepler views: held-out test stars (never trained on) and the training stars dealt into folds.

    Every fold is held out by one ensemble member, so each training star has a prediction from a network that
    never saw it. The second stage is fitted on those out-of-fold predictions; fitted on predictions for stars
    the network had memorised, it would learn to trust the network far more than it deserves.
    """
    from . import kepler
    d = kepler.load_dataset()
    if d is None or len(d["y"]) < 60:
        return None
    rng = np.random.default_rng(7)
    train_stars = rng.permutation(np.unique(d["kepid"][~d["test"]]))  # by star: views of one star stay together
    fold_of_star = {int(k): i % FOLDS for i, k in enumerate(train_stars)}
    fold = np.array([-1 if t else fold_of_star[int(k)] for k, t in zip(d["kepid"], d["test"])])
    train_idx = np.flatnonzero(fold >= 0)
    rank = d["rank"] if "rank" in d else np.zeros(len(d["y"]), int)
    # scored on, and the second stage fitted on, each star's strongest signal: the one a blind run reports first
    return {"data": d, "fold": fold, "fit": train_idx, "val": train_idx[:0], "test": np.flatnonzero(d["test"] & (rank == 0)),
            "stack": np.flatnonzero((fold >= 0) & (rank == 0)),
            "summary": kepler.dataset_summary(), "sample": kepler.load_sample()}


def simulated_stack_samples(n_per_class: int = 300, seed: int = 11):
    """Giant planets and eclipsing binaries, simulated and measured exactly like a real star.

    Hot Jupiters are rare among Kepler's planets, so the real stars alone teach the second stage that a deep dip
    is suspicious in itself. These examples carry the physics instead: a deep dip with equal odd/even depths, no
    secondary eclipse and no centroid motion is a planet; the same depth with any of those is a binary.
    """
    from . import kepler
    from .synthetic import SyntheticSpec, synthesize
    rng = np.random.default_rng(seed)
    g, l, aux, ext, y = [], [], [], [], []
    for cls, kind in ((0, "planet"), (1, "eclipsing_binary"), (1, "blend")):
        made = 0
        for _ in range(n_per_class * 4):
            if made >= (n_per_class if cls == 0 else n_per_class // 2):
                break
            period = float(np.exp(rng.uniform(np.log(1.0), np.log(10.0))))
            r_star = float(rng.uniform(0.8, 1.6))
            spec = SyntheticSpec(kind=kind, period_days=period, depth=float(rng.uniform(0.07, 0.15) ** 2 if cls == 0 else rng.uniform(0.01, 0.06)),
                                 impact_param=float(rng.uniform(0.0, 0.75)), noise_ppm=float(rng.uniform(150, 1500)),
                                 baseline_days=float(rng.choice([27.4, 60.0, 90.0])), cadence_min=float(rng.choice([5.0, 10.0, 30.0])),
                                 variability_amp=0.001, gap=False, outlier_fraction=0.0,
                                 sb_ratio=float(rng.uniform(0.05, 1.0)), dilution=float(rng.uniform(0.2, 1.0)),
                                 seed=int(rng.integers(1 << 31)))
            sim = synthesize(spec, r_star, r_star ** 1.25)
            truth = sim["truth"]
            dur = truth.get("duration_hours") or 24.0 * period * 0.03
            row = {"koi_period": period, "koi_time0bk": truth["t0"], "koi_duration": dur, "koi_steff": 5800.0,
                   "koi_srad": r_star, "koi_smass": r_star ** 1.25}
            lc = {"time": sim["time"], "flux": sim["flux"] / np.median(sim["flux"]),
                  "centroid_col": sim["centroid_col"] - np.median(sim["centroid_col"]),
                  "centroid_row": sim["centroid_row"] - np.median(sim["centroid_row"])}
            v = kepler.koi_views(row, lc)
            if v is None:
                continue
            g.append(v[0]); l.append(v[1]); aux.append(v[2]); ext.append(v[3]); y.append(cls)
            made += 1
    return np.stack(g), np.stack(l), np.stack(aux), np.stack(ext), np.array(y)


def out_of_fold_probs(model, real: dict) -> np.ndarray:
    """For each real row the second stage is fitted on, the prediction of the ensemble member that never saw that star."""
    d, fold = real["data"], real["fold"]
    train = real["stack"]
    members = list(model.members) if isinstance(model, Ensemble) else []
    if len(members) != FOLDS:
        return class_probs(model, d["g"][train], d["l"][train])  # single network: no honest prediction available
    out = np.zeros((len(train), len(CLASS_NAMES)))
    for k, member in enumerate(members):
        rows = fold[train] == k
        if rows.any():
            out[rows] = class_probs(member, d["g"][train][rows], d["l"][train][rows])
    return out


def fit_stacker(model, real: dict, metrics: dict) -> dict | None:
    """Fit the second stage on the real training stars and record its score on the held-out stars."""
    from . import stack
    d = real["data"]
    if "aux" not in d or d["aux"].shape[1] != len(stack.AUX) or "ext" not in d or d["ext"].shape[1] != len(stack.EXTRA):
        return None  # dataset written by an older version: rebuild it to refresh the second stage
    train = real["stack"]
    # keep the simulated giants and binaries in the same proportion to the real examples as the set grows
    sg, sl, saux, sext, sy = simulated_stack_samples(int(np.clip(len(train) // 16, 300, 1000)))
    params = stack.fit(np.concatenate([out_of_fold_probs(model, real), class_probs(model, sg, sl)]),
                       np.concatenate([d["aux"][train], saux]), np.concatenate([d["ext"][train], sext]),
                       np.concatenate([d["y"][train], sy]))
    params["n_real"], params["n_simulated"] = int(len(train)), int(len(sy))
    test = real["test"]
    probs = stack.predict(class_probs(model, d["g"][test], d["l"][test]), d["aux"][test], d["ext"][test], params)
    y = d["y"][test]
    confusion = np.zeros((3, 3), int)
    np.add.at(confusion, (y, probs.argmax(1)), 1)
    fpr, tpr, auc = roc_curve(probs[:, 0], y == 0)
    pick = np.unique(np.linspace(0, len(fpr) - 1, 120).astype(int))
    metrics["real"]["combined"] = {
        "auc_planet": round(auc, 5), "pr_auc_planet": round(average_precision(probs[:, 0], y == 0), 5),
        "accuracy": round(float((probs.argmax(1) == y).mean()), 5), "confusion": confusion.tolist(),
        "roc": {"fpr": np.round(fpr[pick], 4).tolist(), "tpr": np.round(tpr[pick], 4).tolist()},
        "p_planet": [round(float(v), 4) for v in probs[:, 0]],
        "features": stack.FEATURES + stack.EXTRA,
        # how many real planets are called planets, and how many others reach the vetting queue at its default threshold
        "planets_called": [int((probs.argmax(1)[y == 0] == 0).sum()), int((y == 0).sum())],
        "others_queued": [int((probs[y != 0, 0] >= DEFAULT_PIPELINE["planet_confidence"]).sum()), int((y != 0).sum())],
        "planets_queued": [int((probs[y == 0, 0] >= DEFAULT_PIPELINE["planet_confidence"]).sum()), int((y == 0).sum())],
    }
    return params


def evaluate_real(model: nn.Module, real: dict, part: str = "test") -> dict:
    d, idx = real["data"], real[part]
    m = evaluate(model, d["g"][idx], d["l"][idx], d["y"][idx])
    probs = class_probs(model, d["g"][idx], d["l"][idx])
    by_kepid = {r["kepid"]: r for r in real["sample"]}
    m["stars"] = [{"kepid": int(d["kepid"][i]), "name": (by_kepid[int(d["kepid"][i])].get("kepler_name")
                                                         or by_kepid[int(d["kepid"][i])]["kepoi_name"]),
                   "label": int(d["y"][i]), "p": [round(float(v), 4) for v in probs[j]]} for j, i in enumerate(idx)]
    return m


def _fit_member(args) -> tuple[dict, list[dict]]:
    """Train one network on the simulated population plus the real stars outside fold `k` (top level, so it can
    run in a worker process). Returns its best weights and per-epoch history."""
    work, k, seed, epochs, threads = args
    if threads:
        torch.set_num_threads(threads)
    torch.manual_seed(seed)
    with np.load(work) as z:
        g_fit, l_fit, y_fit, gv, lv, yv = z["g"], z["l"], z["y"], z["gv"], z["lv"], z["yv"]
        has_real = "rg" in z.files
        if has_real:
            rg, rl, ry, fold = z["rg"], z["rl"], z["ry"], z["fold"]
    n_sim = len(y_fit)
    real_val = None
    if has_real:
        idx = np.flatnonzero((fold >= 0) & (fold != k))
        held = np.flatnonzero(fold == k)
        real_val = (rg[held], rl[held], ry[held])
        reps = max(1, n_sim // (2 * len(idx)))  # repeat the real stars so they carry about a third of every epoch
        g_fit = np.concatenate([g_fit] + [rg[idx]] * reps)
        l_fit = np.concatenate([l_fit] + [rl[idx]] * reps)
        y_fit = np.concatenate([y_fit] + [ry[idx]] * reps)
    n_fit = len(y_fit)
    gt, lt, yt = torch.from_numpy(g_fit), torch.from_numpy(l_fit), torch.from_numpy(y_fit.astype(np.int64))
    model = DualBranchCNN()
    opt = torch.optim.Adam(model.parameters(), lr=1e-3, weight_decay=1e-5)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
    loss_fn = nn.CrossEntropyLoss()
    history = []
    best_state, best_score = None, -1.0
    for epoch in range(epochs):
        model.train()
        perm = torch.randperm(n_fit)
        running = 0.0
        for i in range(0, n_fit, 128):
            idx_b = perm[i:i + 128]
            gb, lb = gt[idx_b], lt[idx_b]
            if torch.rand(1).item() < 0.5:  # time-reversal augmentation
                gb, lb = gb.flip(-1), lb.flip(-1)
            if torch.rand(1).item() < 0.5:  # which transits count as "odd" is arbitrary
                lb = lb[:, [0, 2, 1, 3], :]
            gb = gb + 0.03 * torch.randn_like(gb)  # mild noise so repeated real stars are never seen identically
            lb = lb + 0.03 * torch.randn_like(lb)
            opt.zero_grad()
            loss = loss_fn(model(gb, lb), yt[idx_b])
            loss.backward()
            opt.step()
            running += loss.item() * len(idx_b)
        sched.step()
        val = evaluate(model, gv, lv, yv)
        row = {"epoch": epoch + 1, "loss": round(running / n_fit, 5), "val_accuracy": val["accuracy"],
               "val_auc_planet": val["auc_planet"]}
        score = val["auc_planet"]
        if real_val is not None and len(real_val[2]) and len(set(real_val[2].tolist())) > 1:
            row["real_val_auc_planet"] = evaluate(model, *real_val)["auc_planet"]
            score = 0.5 * (score + row["real_val_auc_planet"])
        history.append(row)
        if score > best_score:
            best_score = score
            best_state = {name: v.clone() for name, v in model.state_dict().items()}
    return best_state, history


def _fit_members(work, n_members: int, seed: int, epochs: int, report) -> list[tuple[dict, list[dict]]]:
    """All members, in parallel worker processes when possible."""
    import os
    from concurrent.futures import ProcessPoolExecutor, as_completed
    import multiprocessing as mp
    cores = os.cpu_count() or 2
    workers = int(os.environ.get("CTE_TRAIN_WORKERS", min(n_members, max(1, cores // 2))))
    jobs = [(str(work), k, seed + 101 * k, epochs, max(1, cores // workers) if workers > 1 else 0) for k in range(n_members)]
    out: list = [None] * n_members
    if workers > 1 and n_members > 1:
        try:
            with ProcessPoolExecutor(workers, mp_context=mp.get_context("spawn")) as pool:
                futures = {pool.submit(_fit_member, job): job[1] for job in jobs}
                for n, fut in enumerate(as_completed(futures), 1):
                    out[futures[fut]] = fut.result()
                    report(f"Training ensemble ({n}/{n_members} networks)", 0.5 + 0.5 * n / n_members)
            return out
        except Exception:
            out = [None] * n_members  # e.g. no importable __main__: fall back to one after another
    for k, job in enumerate(jobs):
        if out[k] is None:
            out[k] = _fit_member(job[:4] + (0,))
        report(f"Training ensemble ({k + 1}/{n_members} networks)", 0.5 + 0.5 * (k + 1) / n_members)
    return out


def train(n_train: int = 30000, n_val: int = 3000, n_test: int = 6000, epochs: int = 10, seed: int = 20261007,
          progress: Callable[[str, float], None] | None = None, use_real: bool = True,
          keep_champion_if_better: bool = False) -> dict:
    """Train an ensemble on the simulated population plus real Kepler stars (when the dataset has been built),
    evaluate on the held-out partitions and activate - or quarantine - the checkpoint."""
    started = _time.time()
    torch.manual_seed(seed)
    report = (lambda stage, frac: None) if progress is None else progress
    real = _real_split() if use_real else None
    baseline_real = None
    if real and CHECKPOINT.exists():
        try:  # how the outgoing checkpoint does on the same real test stars, for a before/after comparison
            previous = load_metrics() or {}
            b = evaluate_real(get_model(), real)
            baseline_real = {"auc_planet": b["auc_planet"], "accuracy": b["accuracy"],
                             "trained_on_real": bool(previous.get("real"))}
        except Exception:
            baseline_real = None
    total = n_train + n_val + n_test
    g, l, y = make_dataset(total, seed, lambda f: report("Simulating TCE population", 0.5 * f))
    tr, va = slice(0, n_train), slice(n_train, n_train + n_val)
    te = slice(n_train + n_val, total)
    work = MODEL_DIR / "train_work.npz"
    arrays = dict(g=g[tr], l=l[tr], y=y[tr], gv=g[va], lv=l[va], yv=y[va])
    if real:
        d = real["data"]
        arrays.update(rg=d["g"], rl=d["l"], ry=d["y"], fold=real["fold"])
    np.savez(work, **arrays)
    try:
        fitted = _fit_members(work, FOLDS if real else 1, seed, epochs, report)
    finally:
        work.unlink(missing_ok=True)
    members = []
    for state, _ in fitted:
        m = DualBranchCNN()
        m.load_state_dict(state)
        m.eval()
        members.append(m)
    model = Ensemble(members)
    model.eval()
    history = []
    for e in range(epochs):  # the curve shown is the mean over members
        rows = [h[e] for _, h in fitted]
        history.append({"epoch": e + 1, **{key: round(float(np.mean([r[key] for r in rows if key in r])), 5)
                                           for key in ("loss", "val_accuracy", "val_auc_planet", "real_val_auc_planet")
                                           if any(key in r for r in rows)}})

    metrics = evaluate(model, g[te], l[te], y[te])
    passed = metrics["auc_planet"] >= TOLERANCES["auc_min"]
    metrics.update(
        trained_at=datetime.now(timezone.utc).isoformat(), seed=seed, n_train=n_train, n_val=n_val, epochs=epochs,
        history=history, train_seconds=round(_time.time() - started, 1), class_names=CLASS_NAMES,
        status="active" if passed else "quarantined", auc_threshold=TOLERANCES["auc_min"],
        parameters=sum(p.numel() for p in model.parameters()),
        dataset="Simulated TCE population (cte.synthetic), held-out test partition",
    )
    stacker = None
    if real:
        r = evaluate_real(model, real)
        r.update(n_fit=int(len(np.unique(real["data"]["kepid"][real["fit"]]))), n_fit_examples=int(len(real["fit"])),
                 n_val=0, folds=FOLDS, members=len(members), summary=real["summary"], baseline=baseline_real,
                 dataset="Kepler DR24 TCEs (Q1-Q17), Science Office labels updated to NASA's current dispositions, held-out stars")
        metrics["real"] = r
        stacker = fit_stacker(model, real, metrics)
    # Champion / challenger: an automated retrain replaces the active model only if it is not worse on the
    # held-out real stars (which never change, because a star's split depends only on its KIC number).
    if (passed and keep_champion_if_better and real and baseline_real
            and metrics["real"]["auc_planet"] < baseline_real["auc_planet"] - REGRESSION_MARGIN):
        metrics["status"] = "rejected"
    history = load_history()  # read before the metrics file is replaced, so a pre-history checkpoint is recorded once
    # PRD §6: a checkpoint below the AUC floor is quarantined and never activated.
    if metrics["status"] == "active":
        from . import stack
        if stacker:
            stack.save(stacker)
        else:
            stack.STACKER.unlink(missing_ok=True)
            stack.reset_cache()
        torch.save({"members": [m.state_dict() for m in members]}, CHECKPOINT)
        METRICS.write_text(json.dumps(metrics, indent=1))
        global _model
        with _lock:
            _model = model
    else:
        torch.save({"members": [m.state_dict() for m in members]}, QUARANTINE)
        (MODEL_DIR / f"metrics.{metrics['status']}.json").write_text(json.dumps(metrics, indent=1))
    history.append({"trained_at": metrics["trained_at"], "status": metrics["status"], "auc_simulated": metrics["auc_planet"],
                    "auc_real": metrics["real"]["auc_planet"] if real else None,
                    "pr_auc_real": metrics["real"]["pr_auc_planet"] if real else None,
                    "auc_real_combined": (metrics["real"].get("combined") or {}).get("auc_planet") if real else None,
                    "accuracy_real": metrics["real"]["accuracy"] if real else None,
                    "real_stars": real["summary"]["stars"] if real else 0, "real_test": int(len(real["test"])) if real else 0,
                    "champion_auc_real": baseline_real["auc_planet"] if baseline_real else None})
    HISTORY.write_text(json.dumps(history, indent=1))
    return metrics


def load_history() -> list[dict]:
    if HISTORY.exists():
        return json.loads(HISTORY.read_text())
    m = load_metrics()  # a checkpoint trained before the history file existed
    if not m:
        return []
    real = m.get("real") or {}
    return [{"trained_at": m["trained_at"], "status": m["status"], "auc_simulated": m["auc_planet"],
             "auc_real": real.get("auc_planet"), "accuracy_real": real.get("accuracy"),
             "real_stars": (real.get("summary") or {}).get("stars", 0), "real_test": real.get("n_test", 0),
             "champion_auc_real": None}]


_model: DualBranchCNN | None = None
_lock = threading.Lock()


def load_metrics() -> dict | None:
    return json.loads(METRICS.read_text()) if METRICS.exists() else None


def get_model() -> nn.Module:
    global _model
    with _lock:
        if _model is None:
            if not CHECKPOINT.exists():
                raise RuntimeError("No active CNN checkpoint. Train the model first (python manage.py train_model).")
            saved = torch.load(CHECKPOINT, map_location="cpu")
            states = saved["members"] if "members" in saved else [saved]  # a single network, from an older version
            nets = []
            for state in states:
                net = DualBranchCNN()
                net.load_state_dict(state)
                net.eval()
                nets.append(net)
            _model = Ensemble(nets) if len(nets) > 1 else nets[0]
            _model.eval()
        return _model


def predict(global_vec: np.ndarray, local_stack: np.ndarray) -> dict[str, float]:
    """Softmax class probabilities for one target: raw binned global view and the (4, 61) local channel stack."""
    probs = class_probs(get_model(), normalize_view(global_vec)[None], np.asarray(local_stack, np.float32)[None])[0]
    return {name: round(float(p), 4) for name, p in zip(CLASS_NAMES, probs)}


def explain(global_vec: np.ndarray, local_stack: np.ndarray) -> dict:
    """Occlusion saliency: how much the winning class probability drops when each stretch of a view is flattened.

    A window slides across each view and is replaced by the out-of-transit baseline (0); for the local view the
    stretch is flattened in every channel at once. Large positive values mark the bins the network relies on.
    """
    model = get_model()
    g, l = normalize_view(global_vec), np.asarray(local_stack, np.float32)
    cases_g, cases_l = [g], [l]
    for centre in range(GLOBAL_BINS):
        v = g.copy()
        v[max(0, centre - 4):centre + 5] = 0.0
        cases_g.append(v)
        cases_l.append(l)
    for centre in range(LOCAL_BINS):
        v = l.copy()
        v[:, max(0, centre - 2):centre + 3] = 0.0
        cases_g.append(g)
        cases_l.append(v)
    probs = class_probs(model, np.stack(cases_g), np.stack(cases_l))
    cls = int(probs[0].argmax())
    drop = probs[0, cls] - probs[1:, cls]
    channel_drop = []
    for ch in range(LOCAL_CHANNELS):  # how much each kind of evidence matters as a whole
        v = l.copy()
        v[ch] = l[0] if ch in (1, 2) else 0.0
        channel_drop.append(v)
    ch_probs = class_probs(model, np.stack([g] * LOCAL_CHANNELS), np.stack(channel_drop))
    return {"class": CLASS_NAMES[cls], "global": np.round(drop[:GLOBAL_BINS], 4).tolist(),
            "local": np.round(drop[GLOBAL_BINS:], 4).tolist(),
            "channels": [round(float(probs[0, cls] - ch_probs[i, cls]), 4) for i in range(LOCAL_CHANNELS)]}


def refresh_real_metrics() -> dict | None:
    """Re-score the active CNN on the current held-out stars and refit the second stage on the current training stars.

    Used after the labelled dataset has grown but the champion CNN was kept: the reported numbers then describe
    the model as it runs today, on every held-out star now available.
    """
    from . import stack
    real = _real_split()
    metrics = load_metrics()
    if not real or not metrics:
        return None
    cnn = get_model()
    r = evaluate_real(cnn, real)
    r.update(n_fit=metrics.get("real", {}).get("n_fit"), n_val=metrics.get("real", {}).get("n_val"), summary=real["summary"],
             baseline=None, dataset="Kepler DR24 TCEs (Q1-Q17), Science Office labels updated to NASA's current dispositions, held-out stars",
             cnn_trained_on_stars=(metrics.get("real", {}).get("summary") or {}).get("stars"))
    metrics["real"] = r
    params = fit_stacker(cnn, real, metrics)
    if params:
        stack.save(params)
    METRICS.write_text(json.dumps(metrics, indent=1))
    return metrics
