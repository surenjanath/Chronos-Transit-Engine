GLOBAL_BINS, LOCAL_BINS, LOCAL_CHANNELS = 201, 61, 4


class DualBranchCNN(nn.Module):
    def __init__(self):
        super().__init__()

        def block(cin, cout, pool, stride):
            return [nn.Conv1d(cin, cout, 5, padding=2), nn.ReLU(), nn.Conv1d(cout, cout, 5, padding=2), nn.ReLU(),
                    nn.MaxPool1d(pool, stride)]

        self.global_branch = nn.Sequential(*block(1, 16, 5, 2), *block(16, 32, 5, 2), *block(32, 64, 5, 2), nn.Flatten())
        # local branch: four channels - all transits, odd, even, and the window at phase 0.5
        self.local_branch = nn.Sequential(*block(LOCAL_CHANNELS, 24, 7, 2), *block(24, 48, 7, 2), nn.Flatten())
        with torch.no_grad():
            n = self.global_branch(torch.zeros(1, 1, GLOBAL_BINS)).shape[1] + \
                self.local_branch(torch.zeros(1, LOCAL_CHANNELS, LOCAL_BINS)).shape[1]
        self.head = nn.Sequential(nn.Linear(n, 256), nn.ReLU(), nn.Dropout(0.3), nn.Linear(256, 64), nn.ReLU(),
                                  nn.Linear(64, len(CLASS_NAMES)))

    def forward(self, g: torch.Tensor, l: torch.Tensor) -> torch.Tensor:
        return self.head(torch.cat([self.global_branch(g.unsqueeze(1)), self.local_branch(l)], dim=1))


