class Ensemble(nn.Module):
    """Several independently trained networks; the output is the log of their mean class probability."""

    def __init__(self, members: list[DualBranchCNN]):
        super().__init__()
        self.members = nn.ModuleList(members)

    def forward(self, g: torch.Tensor, l: torch.Tensor) -> torch.Tensor:
        p = torch.stack([torch.softmax(m(g, l), dim=1) for m in self.members]).mean(0)
        return torch.log(p.clamp_min(1e-9))


FOLDS = 5


def _time_grid(rng) -> np.ndarray:
    t = np.arange(0.0, 27.4, 10.0 / 1440.0)
    return t[np.abs(t - 13.7) > rng.uniform(0.3, 0.8)]


def _views(t, flux, period, t0, q) -> tuple[np.ndarray, np.ndarray]:
    phase, f, _ = TransitAnalyticsEngine.phase_fold(t, flux, period, t0)
    return normalize_view(global_view(phase, f, GLOBAL_BINS)), local_channels(t, flux, period, t0, q, LOCAL_BINS)


def _red_noise(rng, t, sigma, strength) -> np.ndarray:
    out = np.zeros_like(t)
    for _ in range(rng.integers(1, 4)):
        out += rng.uniform(0.1, 1.0) * strength * sigma * np.sin(2 * np.pi * t / rng.uniform(0.3, 10.0) + rng.uniform(0, 6.28))
    return out


def make_sample(rng: np.random.Generator, cls: int) -> tuple[np.ndarray, np.ndarray]:
    t = _time_grid(rng)
    n = len(t)
    for _ in range(50):
        period = float(np.exp(rng.uniform(np.log(0.6), np.log(13.0))))
        t0 = rng.uniform(0, period)
        if cls == 2:  # stellar / instrumental noise folded on a spurious period
            sigma = 1e-3
            flux = 1.0 + rng.normal(0, sigma, n)
            if rng.random() < 0.6:
                flux += _red_noise(rng, t, sigma, rng.uniform(0.3, 2.0))
            if rng.random() < 0.25:
                for _ in range(rng.integers(1, 4)):
                    c, w = rng.uniform(0, 27.4), rng.uniform(0.04, 0.2)
                    flux -= rng.uniform(3, 8) * sigma * np.exp(-0.5 * ((t - c) / w) ** 2)
            # BLS picks the deepest box, so centre the fold on the lowest phase bin
            phase, f, _ = TransitAnalyticsEngine.phase_fold(t, flux, period, t0)
            t0 += (np.argmin(global_view(phase, f, GLOBAL_BINS)) + 0.5) / GLOBAL_BINS * period - 0.5 * period
            return _views(t, flux, period, t0, rng.uniform(0.01, 0.1))

        r_star = rng.uniform(0.5, 1.6)
        a_rs = a_over_rstar(period, r_star ** 1.25, r_star)
        if cls == 0:
            k = float(np.exp(rng.uniform(np.log(0.02), np.log(0.16))))
            b = rng.uniform(0.0, 0.9)
            if a_rs < 2.0:
                continue
            signal = transit_flux(t, period, t0, k, a_rs, b, (rng.uniform(0.2, 0.6), rng.uniform(0.1, 0.35)))
            depth_sig = 1.0 - signal.min()
        else:
            k = rng.uniform(0.2, 1.0)
            sb = float(np.exp(rng.uniform(np.log(0.03), 0.0)))
            b = rng.uniform(0.0, 1.0 + 0.9 * k)
            a_rs *= 1.26
            if a_rs < 1.3 + k:
                continue
            dilution = float(np.exp(rng.uniform(np.log(0.03), 0.0))) if rng.random() < 0.4 else 1.0
            signal = eclipsing_binary_flux(t, period, t0, k, a_rs, b, sb, dilution)
            depth_sig = 1.0 - signal.min()
        arg = np.sqrt(max((1 + k) ** 2 - b * b, 0.0)) / a_rs
        t14 = period / np.pi * np.arcsin(min(arg, 1.0))
        n_in = n * t14 / period
        if depth_sig <= 0 or n_in < 3:
            continue
        snr = float(np.exp(rng.uniform(np.log(8.0), np.log(300.0))))
        sigma = depth_sig * np.sqrt(n_in) / snr
        if cls == 1:
            front = np.cos(2 * np.pi * (t - t0) / period) > 0
            sec = 1.0 - signal[~front].min() if (~front).any() else 0.0
            # keep only binaries that carry a learnable signature
            if not (sec * np.sqrt(n_in) / sigma > 5.0 or b > 1.0 - k or k >= 0.3):
                continue
        flux = signal + rng.normal(0, sigma, n) + _red_noise(rng, t, sigma, rng.uniform(0.0, 0.4))
        q = float(np.clip(t14 / period * rng.uniform(0.75, 1.3), 0.004, 0.15))
        return _views(t, flux, period * (1 + rng.normal(0, 2e-5)), t0 + rng.normal(0, 0.03 * t14), q)
    raise RuntimeError("failed to draw a valid training sample")


def make_dataset(n: int, seed: int, progress: Callable[[float], None] | None = None):
    rng = np.random.default_rng(seed)
    g = np.empty((n, GLOBAL_BINS), np.float32)
    l = np.empty((n, LOCAL_CHANNELS, LOCAL_BINS), np.float32)
    y = rng.integers(0, len(CLASS_NAMES), n)
    for i in range(n):
        g[i], l[i] = make_sample(rng, int(y[i]))
        if progress and i % 500 == 0:
            progress(i / n)
    return g, l, y.astype(np.int64)


