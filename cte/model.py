"""Dual-branch 1D-CNN classifier (PRD §3).

Global branch (201 bins) sees the whole orbit - out-of-transit variation and
secondary eclipses. Local branch (61 bins) sees the ingress/egress profile.
Softmax output: [P_planet, P_binary, P_noise].

The network is trained on a simulated TCE population generated by
`cte.synthetic` and pushed through the same fold/bin code as live data.
"""
