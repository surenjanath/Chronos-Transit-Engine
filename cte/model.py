def roc_curve(scores: np.ndarray, positive: np.ndarray) -> tuple[np.ndarray, np.ndarray, float]:
    order = np.argsort(-scores, kind="stable")
    pos = positive[order].astype(float)
    tpr = np.concatenate(([0.0], np.cumsum(pos) / max(pos.sum(), 1)))
    fpr = np.concatenate(([0.0], np.cumsum(1 - pos) / max((1 - pos).sum(), 1)))
    return fpr, tpr, float(np.trapezoid(tpr, fpr))


def class_probs(model: nn.Module, g: np.ndarray, l: np.ndarray) -> np.ndarray:
    """Softmax probabilities averaged over the views and their time-reversed mirror images."""
    model.eval()
    gt, lt = torch.from_numpy(np.ascontiguousarray(g)), torch.from_numpy(np.ascontiguousarray(l))
    with torch.no_grad():
        return (0.5 * (torch.softmax(model(gt, lt), dim=1) + torch.softmax(model(gt.flip(-1), lt.flip(-1)), dim=1))).numpy()


def average_precision(scores: np.ndarray, positive: np.ndarray) -> float:
    """Area under the precision-recall curve (PR-AUC), as the mean precision at each true positive."""
    order = np.argsort(-scores, kind="stable")
    pos = positive[order].astype(float)
    if pos.sum() == 0:
        return float("nan")
    precision = np.cumsum(pos) / (np.arange(len(pos)) + 1)
    return float((precision * pos).sum() / pos.sum())


def evaluate(model: nn.Module, g, l, y) -> dict:
    probs = class_probs(model, g, l)
    pred = probs.argmax(1)
    confusion = np.zeros((3, 3), int)
    np.add.at(confusion, (y, pred), 1)
    aucs, rocs = {}, {}
    for c, name in enumerate(CLASS_NAMES):
        fpr, tpr, auc = roc_curve(probs[:, c], y == c)
        aucs[name] = round(auc, 5)
        pick = np.unique(np.linspace(0, len(fpr) - 1, 120).astype(int))
        rocs[name] = {"fpr": np.round(fpr[pick], 4).tolist(), "tpr": np.round(tpr[pick], 4).tolist()}
    return {
        "accuracy": round(float((pred == y).mean()), 5),
        "auc": aucs,
        "auc_planet": aucs[CLASS_NAMES[0]],
        "pr_auc_planet": round(average_precision(probs[:, 0], y == 0), 5),
        "auc_macro": round(float(np.mean(list(aucs.values()))), 5),
        "confusion": confusion.tolist(),
        "roc": rocs,
        "n_test": int(len(y)),
    }


